#!/usr/bin/env python3
"""Independent OpenSSL/hashlib vectors for the added SHA-2 and SHAKE variants."""
import hashlib
import pathlib
import sys

algorithms = {
    "SHA-512/224": ("sha512_224", None),
    "SHA-512/256": ("sha512_256", None),
    "SHAKE128-256": ("shake_128", 32),
    "SHAKE256-512": ("shake_256", 64),
}
data = bytes((i * 71 + 19) & 255 for i in range(2 * 1024 * 1024 + 17))
lines = ["// Generated by GenerateHashVectors.py using Python hashlib/OpenSSL.",
         "// Input byte i is (i * 71 + 19) & 255; sizes exercise padding/block boundaries.",
         "struct HashVector { const char* name; size_t size; const char* expected; };",
         "static constexpr HashVector additional_vectors[] = {"]
for name, (algorithm, output_length) in algorithms.items():
    for size in (0, 1, 63, 64, 65, 111, 112, 127, 128, 129, 135, 136, 167, 168, 8191, 8192, 8193, len(data)):
        context = hashlib.new(algorithm, data[:size])
        digest = context.hexdigest(output_length) if output_length else context.hexdigest()
        lines.append(f'  {{"{name}", {size}, "{digest}"}},')
lines.append("};")
expected = "\n".join(lines) + "\n"
path = pathlib.Path(__file__).with_name("AdditionalHashVectors.h")
if "--check" in sys.argv:
    if path.read_text() != expected:
        raise SystemExit("Independent hash vectors do not match the checked-in fixture")
    print(f"PASS: {len(algorithms) * 18} independent hash vectors")
else:
    path.write_text(expected)
